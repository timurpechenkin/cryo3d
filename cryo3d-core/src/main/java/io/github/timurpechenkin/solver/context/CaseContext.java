package io.github.timurpechenkin.solver.context;

import java.time.LocalDateTime;

import io.github.timurpechenkin.domain.bc.BoundaryConditionType;
import io.github.timurpechenkin.domain.grid.Grid3D;
import io.github.timurpechenkin.geometry.Axis3D;
import io.github.timurpechenkin.geometry.Face;

/**
 * Изменяемое runtime-состояние расчёта теплопереноса.
 *
 * <p>
 * Контекст представляет модель среды и инкапсулирует зависимость
 * теплофизических свойств материалов от текущего состояния системы
 * (в первую очередь — от температуры).
 *
 * <p>
 * В рамках архитектуры расчёта роли разделены следующим образом:
 * <ul>
 * <li>{@code CaseContext} определяет, какими являются эффективные
 * свойства материала при текущем состоянии системы;</li>
 * <li>{@code StepCalculator} определяет, как изменяется состояние системы
 * за один шаг времени при заданных свойствах среды.</li>
 * </ul>
 *
 * <p>
 * Контекст хранит:
 * <ul>
 * <li>расчётную геометрию;</li>
 * <li>текущее температурное поле;</li>
 * <li>логику вычисления эффективных теплофизических свойств;</li>
 * <li>текущее время контекста;</li>
 * <li>доступ к параметрам граничных условий.</li>
 * </ul>
 *
 * <p>
 * <b>Важно:</b> значения теплопроводности и объёмной теплоёмкости,
 * возвращаемые контекстом, могут быть нелинейными функциями температуры
 * и определяются конкретной реализацией.
 *
 * <p>
 * Контекст является изменяемым runtime-объектом и не потокобезопасен.
 * Он предназначен для использования одним солвером
 * в рамках одного расчёта.
 */
public interface CaseContext {

    /**
     * Возвращает расчётную 3D-сетку.
     *
     * <p>
     * Может использоваться численной схемой для доступа к геометрии:
     * шагам, центрам, объёмам ячеек и другим характеристикам сетки.
     *
     * @return расчётная 3D-сетка
     */
    Grid3D grid();

    /**
     * Возвращает линейный индекс ячейки по позиции {@code (x, y, z)}.
     *
     * @param x позиция по оси X
     * @param y позиция по оси Y
     * @param z позиция по оси Z
     * @return линейный индекс ячейки
     * @throws IndexOutOfBoundsException если позиция выходит за пределы сетки
     */
    int idx(int x, int y, int z);

    /**
     * Возвращает идентификатор материала в указанной ячейке.
     *
     * @param x позиция по оси X
     * @param y позиция по оси Y
     * @param z позиция по оси Z
     * @return идентификатор материала в библиотеке материалов
     */
    int materialId(int x, int y, int z);

    // -----------------------------------------------
    // ТЕПЛОФИЗИЧЕСКИЕ ХАРАКТЕРИСТИКИ
    // -----------------------------------------------

    /**
     * Возвращает теплопроводность ячейки
     * при текущем температурном состоянии, [Вт/(м·К)]
     *
     * <p>
     * Конкретное значение определяется реализацией контекста
     * на основе текущей температуры и модели состояния грунта.
     *
     * @param x позиция по оси X
     * @param y позиция по оси Y
     * @param z позиция по оси Z
     * @return эффективная теплопроводность
     */
    double thermalConductivity(int x, int y, int z);

    double thermalConductivity(int index);

    /**
     * Возвращает объёмную теплоёмкость ячейки
     * при текущем температурном состоянии, [Дж/(м3·К)]
     *
     * <p>
     * Конкретное значение определяется реализацией контекста
     * на основе текущей температуры и модели состояния грунта.
     *
     * @param x позиция по оси X
     * @param y позиция по оси Y
     * @param z позиция по оси Z
     * @return эффективная теплоёмкость
     */
    double volumetricHeatCapacity(int x, int y, int z);

    double volumetricHeatCapacity(int index);

    /**
     * Возвращает скрытую теплоту фазового перехода для ячейки, [Дж/м3]
     *
     * @param x позиция по оси X
     * @param y позиция по оси Y
     * @param z позиция по оси Z
     * @return скрытая теплота фазового перехода
     */
    double phaseTransitionsHeat(int x, int y, int z);

    double phaseTransitionsHeat(int index);

    /**
     * Возвращает температуру замерзания материала в ячейке, [C]
     *
     * @param x позиция по оси X
     * @param y позиция по оси Y
     * @param z позиция по оси Z
     * @return температура замерзания
     */
    double freezingTemperature(int x, int y, int z);

    double freezingTemperature(int index);

    // -----------------------------------------------
    // ГРАНИЧНЫЕ УСЛОВИЯ
    // -----------------------------------------------

    /**
     * Проверяет, лежит ли указанная грань ячейки на внешней границе расчётной
     * области.
     *
     * @param x    позиция по оси X
     * @param y    позиция по оси Y
     * @param z    позиция по оси Z
     * @param face грань ячейки
     * @return {@code true}, если указанная грань является внешней границей области
     */
    boolean hasBoundaryCondition(int x, int y, int z, Face face);

    /**
     * Проверяет есть ли у ячейки граничное условие на указанной грани
     * 
     * @param x    позиция по оси X
     * @param y    позиция по оси Y
     * @param z    позиция по оси Z
     * @param face грань ячейки
     * @return род граничного условия
     * @throws IllegalArgumentException если указанная грань не является
     *                                  внешней границей области
     */
    BoundaryConditionType boundaryConditionType(int x, int y, int z, Face face);

    /**
     * Возвращает температуру на границе для граничного условия I рода, [°C].
     *
     * <p>
     * Если параметры граничного условия зависят от времени,
     * возвращается значение для текущего времени контекста.
     *
     * @param x    позиция по оси X
     * @param y    позиция по оси Y
     * @param z    позиция по оси Z
     * @param face грань ячейки
     * @return температура на границе, °C
     * @throws IllegalArgumentException если указанная грань не является внешней
     *                                  границей области
     */
    double boundaryTemperatureC(int x, int y, int z, Face face);

    /**
     * Возвращает плотность теплового потока для граничного условия II рода,
     * [Вт/м²].
     *
     * <p>
     * Положительное направление потока должно интерпретироваться
     * численной схемой единообразно во всём расчёте.
     * Если параметры граничного условия зависят от времени,
     * возвращается значение для текущего времени контекста.
     *
     * @param x    позиция по оси X
     * @param y    позиция по оси Y
     * @param z    позиция по оси Z
     * @param face грань ячейки
     * @return плотность теплового потока, Вт/м²
     * @throws IllegalArgumentException если указанная грань не является внешней
     *                                  границей области
     */
    double boundaryHeatFlux(int x, int y, int z, Face face);

    /**
     * Возвращает температуру внешней среды для граничного условия III рода, [°C].
     *
     * <p>
     * Если параметры граничного условия зависят от времени,
     * возвращается значение для текущего времени контекста.
     *
     * @param x    позиция по оси X
     * @param y    позиция по оси Y
     * @param z    позиция по оси Z
     * @param face грань ячейки
     * @return температура внешней среды, °C
     * @throws IllegalArgumentException если указанная грань не является внешней
     *                                  границей области
     */
    double boundaryAmbientTemperatureC(int x, int y, int z, Face face);

    /**
     * Возвращает коэффициент теплообмена для граничного условия III рода,
     * [Вт/(м²·К)].
     *
     * <p>
     * Если параметры граничного условия зависят от времени,
     * возвращается значение для текущего времени контекста.
     *
     * @param x    позиция по оси X
     * @param y    позиция по оси Y
     * @param z    позиция по оси Z
     * @param face грань ячейки
     * @return коэффициент теплообмена, Вт/(м²·К)
     * @throws IllegalArgumentException если указанная грань не является внешней
     *                                  границей области
     */
    double boundaryHeatTransferCoeff(int x, int y, int z, Face face);

    // -----------------------------------------------
    // ТЕМПЕРАТУРНОЕ ПОЛЕ
    // -----------------------------------------------

    /**
     * Возвращает текущую температуру ячейки, [C]
     *
     * @param x позиция по оси X
     * @param y позиция по оси Y
     * @param z позиция по оси Z
     * @return текущая температура ячейки, °C
     */
    double temperatureC(int x, int y, int z);

    double temperatureC(int cellIndex);

    /**
     * Заменяет текущее температурное поле новым состоянием системы.
     *
     * <p>
     * Обычно вызывается после завершения очередного шага расчёта,
     * когда численная схема сформировала новое температурное поле.
     *
     * @param newTemperature новое температурное поле по всем ячейкам
     * @throws NullPointerException  если {@code newTemperature == null}
     * @throws IllegalStateException если длина массива не совпадает
     *                               с числом ячеек расчётной сетки
     */
    void setNewTemperature(double[] newTemperature);

    /**
     * Возвращает текущее температурное поле по всем ячейкам.
     *
     * <p>
     * <b>Важно:</b> возвращается внутренняя ссылка на массив,
     * а не его копия. Изменение содержимого этого массива
     * приводит к изменению состояния контекста.
     *
     * @return текущее температурное поле, °C
     */
    double[] currentTemperatureByCell();

    // -----------------------------------------------
    // ВРЕМЯ
    // -----------------------------------------------

    /**
     * Возвращает начальный момент времени контекста.
     *
     * @return начальная дата и время расчёта
     */
    LocalDateTime getStartDate();

    /**
     * Возвращает текущее время контекста.
     *
     * @return текущая дата и время расчёта
     */
    LocalDateTime getCurrentDate();

    /**
     * Устанавливает текущее время контекста как смещение
     * относительно начального момента расчёта.
     *
     * @param seconds число секунд от начала расчёта
     */
    void setCurrentTime(long seconds);

    // -----------------------------------------------
    // ГЕОМЕТРИЯ
    // -----------------------------------------------

    double cellSideMeters(int x, int y, int z, Axis3D axis3d);

    double areaNormalToAxisMeters2(int x, int y, int z, Axis3D axis3d);

    double volumeMeters3(int x, int y, int z);

    double cellSideMeters(int index, Axis3D axis3d);

    double areaNormalToAxisMeters2(int index, Axis3D axis3d);

    double volumeMeters3(int index);

    // -----------------------------------------------
    // ЭНТАЛЬПИЯ
    // -----------------------------------------------

    /**
     * Возвращает текущую энтальпию ячейки, [Дж/м³].
     *
     * @param x позиция по оси X
     * @param y позиция по оси Y
     * @param z позиция по оси Z
     * @return текущая энтальпия ячейки
     */
    double enthalpy(int x, int y, int z);

    /**
     * Возвращает текущую энтальпию ячейки по линейному индексу, [Дж/м³].
     *
     * @param cellIndex линейный индекс ячейки
     * @return текущая энтальпия ячейки
     */
    double enthalpy(int cellIndex);

    /**
     * Возвращает долю талой фазы в ячейке.
     *
     * <p>
     * Для минимальной энтальпийной схемы эта величина может не храниться
     * отдельно, а вычисляться из энтальпии на лету.
     *
     * @param x позиция по оси X
     * @param y позиция по оси Y
     * @param z позиция по оси Z
     * @return доля талой фазы в диапазоне {@code [0, 1]}
     */
    double thawedFraction(int x, int y, int z);

    /**
     * Возвращает долю талой фазы в ячейке.
     *
     * <p>
     * Для минимальной энтальпийной схемы эта величина может не храниться
     * отдельно, а вычисляться из энтальпии на лету.
     *
     * @param cellIndex линейный индекс ячейки
     * @return доля талой фазы в диапазоне {@code [0, 1]}
     */
    double thawedFraction(int cellIndex);

    /**
     * Возвращает текущее энтальпийное поле, [Дж/м³].
     *
     * <p>
     * Как и для температурного поля, возвращается внутренняя ссылка на массив.
     *
     * @return текущее энтальпийное поле
     */
    double[] currentEnthalpyByCell();

    /**
     * Заменяет текущее энтальпийное поле новым состоянием системы.
     *
     * <p>
     * После вызова этого метода контекст должен согласованно обновить
     * производные величины, зависящие от энтальпии, в первую очередь
     * температурное поле.
     *
     * @param newEnthalpy новое энтальпийное поле, [Дж/м³]
     */
    void setNewEnthalpy(double[] newEnthalpy);
}