package io.github.timurpechenkin.solver.context;

import io.github.timurpechenkin.domain.grid.Grid3D;

/**
 * Модель состояния среды (материала) в задаче теплопереноса.
 *
 * <p>
 * Контекст инкапсулирует зависимость теплофизических свойств
 * материалов от текущего состояния системы (в первую очередь — температуры).
 * Таким образом, {@code CaseContext} выступает как модель среды,
 * предоставляя эффективные параметры (теплопроводность, теплоёмкость и т.д.)
 * в зависимости от текущего температурного состояния.
 *
 * <p>
 * Контекст также хранит текущее температурное поле и позволяет
 * заменить его новым состоянием, полученным после очередного шага расчёта.
 *
 * <p>
 * Контекст предоставляет:
 * <ul>
 * <li>доступ к геометрии расчётной сетки;</li>
 * <li>доступ к текущему температурному полю;</li>
 * <li>вычисление эффективных теплофизических свойств ячеек
 * при текущей температуре;</li>
 * <li>обновление температурного состояния системы.</li>
 * </ul>
 *
 * <p>
 * <b>Важно:</b> значения теплопроводности и теплоёмкости,
 * возвращаемые контекстом, могут быть нелинейными функциями температуры
 * и определяются конкретной реализацией контекста.
 *
 * <p>
 * Контекст является изменяемым runtime-объектом и не потокобезопасен.
 * Он предназначен для использования одним солвером
 * в рамках одного расчёта.
 */
public interface CaseContext {

    /**
     * Возвращает расчётную 3D-сетку.
     *
     * <p>
     * Может использоваться численной схемой для доступа к геометрии:
     * шагам, центрам, объёмам ячеек и другим характеристикам сетки.
     *
     * @return расчётная 3D-сетка
     */
    Grid3D grid();

    /**
     * Возвращает линейный индекс ячейки по позиции {@code (x, y, z)}.
     *
     * @param x позиция по оси X
     * @param y позиция по оси Y
     * @param z позиция по оси Z
     * @return линейный индекс ячейки
     * @throws IndexOutOfBoundsException если позиция выходит за пределы сетки
     */
    int idx(int x, int y, int z);

    /**
     * Возвращает идентификатор материала в указанной ячейке.
     *
     * @param x позиция по оси X
     * @param y позиция по оси Y
     * @param z позиция по оси Z
     * @return индекс материала в библиотеке материалов
     */
    int materialId(int x, int y, int z);

    /**
     * Возвращает эффективную теплопроводность ячейки
     * при текущем температурном состоянии.
     *
     * <p>
     * Конкретное значение определяется реализацией контекста
     * на основе текущей температуры и модели состояния грунта.
     *
     * @param x позиция по оси X
     * @param y позиция по оси Y
     * @param z позиция по оси Z
     * @return эффективная теплопроводность
     */
    double thermalConductivity(int x, int y, int z);

    /**
     * Возвращает эффективную теплоёмкость ячейки
     * при текущем температурном состоянии.
     *
     * <p>
     * Конкретное значение определяется реализацией контекста
     * на основе текущей температуры и модели состояния грунта.
     *
     * @param x позиция по оси X
     * @param y позиция по оси Y
     * @param z позиция по оси Z
     * @return эффективная теплоёмкость
     */
    double heatCapacity(int x, int y, int z);

    /**
     * Возвращает скрытую теплоту фазового перехода для ячейки.
     *
     * @param x позиция по оси X
     * @param y позиция по оси Y
     * @param z позиция по оси Z
     * @return скрытая теплота фазового перехода
     */
    double phaseTransitionsHeat(int x, int y, int z);

    /**
     * Возвращает температуру замерзания материала в ячейке.
     *
     * @param x позиция по оси X
     * @param y позиция по оси Y
     * @param z позиция по оси Z
     * @return температура замерзания
     */
    double freezingTemperature(int x, int y, int z);

    /**
     * Возвращает текущую температуру ячейки в градусах Цельсия.
     *
     * @param x позиция по оси X
     * @param y позиция по оси Y
     * @param z позиция по оси Z
     * @return текущая температура ячейки, °C
     */
    double temperatureC(int x, int y, int z);

    /**
     * Возвращает эффективную теплопроводность ячейки
     * по линейному индексу.
     *
     * @param cellIndex линейный индекс ячейки
     * @return эффективная теплопроводность
     */
    double thermalConductivity(int cellIndex);

    /**
     * Возвращает эффективную теплоёмкость ячейки
     * по линейному индексу.
     *
     * @param cellIndex линейный индекс ячейки
     * @return эффективная теплоёмкость
     */
    double heatCapacity(int cellIndex);

    /**
     * Возвращает скрытую теплоту фазового перехода
     * по линейному индексу ячейки.
     *
     * @param cellIndex линейный индекс ячейки
     * @return скрытая теплота фазового перехода
     */
    double phaseTransitionsHeat(int cellIndex);

    /**
     * Возвращает температуру замерзания
     * по линейному индексу ячейки.
     *
     * @param cellIndex линейный индекс ячейки
     * @return температура замерзания
     */
    double freezingTemperature(int cellIndex);

    /**
     * Возвращает текущую температуру ячейки
     * по линейному индексу.
     *
     * @param cellIndex линейный индекс ячейки
     * @return текущая температура, °C
     */
    double temperatureC(int cellIndex);

    /**
     * Заменяет текущее температурное поле новым состоянием системы.
     *
     * <p>
     * Обычно вызывается после завершения очередного шага расчёта,
     * когда численная схема сформировала новое температурное поле.
     *
     * @param newTemperature новое температурное поле по всем ячейкам
     * @throws NullPointerException  если {@code newTemperature == null}
     * @throws IllegalStateException если длина массива не совпадает
     *                               с числом ячеек расчётной сетки
     */
    void setNewTemperature(double[] newTemperature);

    /**
     * Возвращает текущее температурное поле по всем ячейкам.
     *
     * <p>
     * <b>Важно:</b> возвращается внутренняя ссылка на массив,
     * а не его копия. Изменение содержимого этого массива
     * приводит к изменению состояния контекста.
     *
     * @return текущее температурное поле, °C
     */
    double[] currentTemperatureByCell();
}